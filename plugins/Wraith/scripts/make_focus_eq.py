"""Writes Source/dsp/FocusEq.h from nulltest/renders/focus_eq2_rates.json: the sections and all-passes of fit_focus_eq.py and
fit_allpass.py (--n 4 and --joint), the top two sections per sample rate, and where fitted every section and the
all-passes per sample rate (fit_focus_hf.py).

    python make_focus_eq.py [file in nulltest/renders/]
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
m = json.load(open(os.path.join(HERE, '..', 'nulltest', 'renders', sys.argv[1] if len(sys.argv) > 1 else 'focus_eq2_rates.json')))
kinds = {'hp': 'HighPass', 'lp': 'LowPass', 'pk': 'Peak', 'ls': 'LowShelf', 'hs': 'HighShelf'}
lines = ['#pragma once', '', '// Generated by scripts/make_focus_eq.py from the fits in nulltest/fit_focus_eq.py, fit_allpass.py and fit_focus_hf.py.',
         '// Do not edit',
         '// by hand. The Character stage\'s Focus EQ (MEASUREMENTS.md "Character"): RBJ sections (w0 = 2 pi f / fs) whose gains',
         '// move with Focus as gain = a + b * Focus / 50, then fixed second-order all-passes and a fractional delay.',
         'namespace wr::dsp::focuseq', '{', 'enum Kind { HighPass, LowPass, Peak, LowShelf, HighShelf };',
         'struct Section { Kind kind; double hz, q, a, b; };', 'inline constexpr Section sections[] {']
for s in m['sections']:
    a, b = (s[3], s[4]) if len(s) > 3 else (0.0, 0.0)
    lines.append(f'    {{ {kinds[s[0]]}, {s[1]!r}, {s[2]!r}, {a!r}, {b!r} }},')
lines += ['};', 'struct AllPass { double hz, q; };', 'inline constexpr AllPass allpasses[] {']
for hz, q in m['allpass']:
    lines.append(f'    {{ {hz!r}, {q!r} }},')
lines += ['};', f'inline constexpr double delaySamples = {m["delay"]!r};    // at 48 kHz',
          '// per sample rate, the sections fitted at that rate (the top two, or every one; the nearest rate applies)',
          'struct RateSection { double fs; unsigned index; double hz, q, a, b; };', 'inline constexpr RateSection rateSections[] {']
for fs, entries in sorted(m.get('rates', {}).items(), key=lambda kv: float(kv[0])):
    for k, (hz, q, a, b) in sorted(entries.items(), key=lambda kv: int(kv[0])):
        lines.append(f'    {{ {float(fs)!r}, {int(k)}, {hz!r}, {q!r}, {a!r}, {b!r} }},')
lines += ['};', '// per sample rate, the all-passes (fitted at that rate; fs 0: none)',
          'struct RateAllPass { double fs; unsigned index; double hz, q; };', 'inline constexpr RateAllPass rateAllpasses[] {']
aps = sorted(m.get('rate_allpass', {}).items(), key=lambda kv: float(kv[0]))
for fs, entries in aps:
    for k, (hz, q) in enumerate(entries):
        lines.append(f'    {{ {float(fs)!r}, {k}, {hz!r}, {q!r} }},')
if not aps:
    lines.append('    { 0.0, 0, 0.0, 0.0 },')
lines += ['};', '}', '']
open(os.path.join(HERE, '..', 'Source', 'dsp', 'FocusEq.h'), 'w', newline='\n').write('\n'.join(lines))
print('wrote FocusEq.h:', len(m['sections']), 'sections,', len(m['allpass']), 'all-passes, delay', m['delay'])
