"""Writes the trained models into Source/dsp/LearnedModels.h: GRU models (train_gru.py's <case>_gru<hidden>.pt) as
LearnedWeights (Learned.h), WaveNets (train_wn.py's <case>_wn.pt) as WaveNetWeights (LearnedWaveNet.h).
    python export_models.py [--merge] [--rest=<name>,...] <name>=<file.pt>[:<tail dB>] ...      e.g. driveA=drive_a_wn.pt grit=grit_wn.pt:-60
--merge keeps the models already in LearnedModels.h, replacing or adding only the ones named. --rest names WaveNets
whose output on silence is taken off their output bias (as the LSTMs' always is)."""
import os, sys
import numpy as np
import torch
import harness as o

NN = os.path.join(o.ROOT, 'measurements', 'scorpius', 'nn')


def trimmed(h, floor_db=-80.0, minimum=64):
    """the long post filter without its tail below floor_db re its energy (the convolver's cost grows with its length)"""
    h = np.asarray(h, np.float64).ravel()
    if not np.any(h): return h[:minimum]            # (a zero filter: train_gain.py's models)
    tail = np.cumsum((h ** 2)[::-1])[::-1] / np.sum(h ** 2)
    keep = np.nonzero(tail > 10 ** (floor_db / 10))[0]
    n = max(minimum, int(keep[-1]) + 1 if len(keep) else minimum)
    return h[:min(len(h), (n + 63) // 64 * 64)]


def arr(v):
    v = np.asarray(v, np.float32).ravel()
    return '{ ' + ', '.join(lit(x) for x in v) + ' }'


def fast_tanh(x):
    """FastMath.h's fastTanh, in float32"""
    x = np.clip(x, np.float32(-4.97), np.float32(4.97)); x2 = x * x
    return (x * (135135 + x2 * (17325 + x2 * (378 + x2))) / (135135 + x2 * (62370 + x2 * (3150 + x2 * 28)))).astype(np.float32)


def tail_sigmoid(x):
    """FastMath.h's tailSigmoid, in float32"""
    u = np.clip(-x, np.float32(-80), np.float32(80)).astype(np.float32) * np.float32(1 / 256)
    e = ((12 + u * (6 + u)) / (12 + u * (u - 6))).astype(np.float32)
    for _ in range(8): e = e * e
    return (np.float32(1) / (np.float32(1) + e)).astype(np.float32)


def wavenet_rest(s, d):
    """the WaveNet's output once settled on silence, as LearnedWaveNet.h computes it (float, FastMath.h's activations):
    with no input every layer holds constants, so each dilated convolution is the sum of its taps"""
    f = lambda k: s[k].numpy().astype(np.float32)
    h = f('wn.inp.bias'); acc = np.zeros_like(h); C = len(h)
    sig = lambda v: np.float32(0.5) + np.float32(0.5) * fast_tanh(np.float32(0.5) * v)
    for i in range(d['layers']):
        z = f(f'wn.conv.{i}.weight').sum(-1) @ h + f(f'wn.conv.{i}.bias')
        g = fast_tanh(z[:C]) * sig(z[C:]) if len(z) == 2 * C else fast_tanh(z)
        h = h + f(f'wn.res.{i}.weight')[:, :, 0] @ g + f(f'wn.res.{i}.bias')
        acc = acc + f(f'wn.skip.{i}.weight')[:, :, 0] @ g + f(f'wn.skip.{i}.bias')
    return float(f('wn.out.weight')[0, :, 0] @ np.maximum(acc, 0) + f('wn.out.bias')[0])


def lstm_rest(s, H, layers, n=96000):
    """the stacked LSTM's output after n samples of silence, as LearnedLSTM.h runs it, and its state then (h, c per
    layer)"""
    W = [(s[f'gru.weight_ih_l{l}'].numpy(), s[f'gru.weight_hh_l{l}'].numpy(),
          (s[f'gru.bias_ih_l{l}'] + s[f'gru.bias_hh_l{l}']).numpy()) for l in range(layers)]
    h = [np.zeros(H, np.float32) for _ in range(layers)]; c = [np.zeros(H, np.float32) for _ in range(layers)]
    sig = tail_sigmoid
    for _ in range(n):
        x = np.zeros(1, np.float32)
        for l, (wi, wh, b) in enumerate(W):
            g = b + wi @ x + wh @ h[l]
            c[l] = sig(g[H:2 * H]) * c[l] + sig(g[:H]) * fast_tanh(g[2 * H:3 * H])
            h[l] = sig(g[3 * H:]) * fast_tanh(c[l]); x = h[l]
    return float(s['out.weight'][0].numpy() @ x + s['out.bias'][0].numpy()), h, c


def flags(d, s):
    """the WaveNet's optional fields (bypass, conds, kernel), written when any differs from its default"""
    k = int(s['wn.conv.0.weight'].shape[-1]); mix = 'wn.mix.0.weight' in s
    if not d.get('bypass') and not d.get('cond') and k == 2 and not mix: return ''
    out = f", {'true' if d.get('bypass') else 'false'}, {1 if d.get('cond') else 0}, {k}"
    if mix: out += ', { ' + ', '.join(arr(s[f'wn.mix.{i}.weight']) for i in range(d['layers'])) + ' }'
    return out


def lit(x):
    """a C++ float literal (1 -> 1.f: '1f' is not one)"""
    t = f'{x:.9g}'
    return t + ('f' if any(c in t for c in '.e') else '.f')


if __name__ == '__main__':
    lines = ['#pragma once', '// Generated by nulltest/export_models.py: the learned modules (Learned.h), trained by nulltest/train_wn.py / train_gru.py on',
             '// the reference\'s input and output. Our own weights.', '#include "Learned.h"', '#include "LearnedLSTM.h"', '#include "LearnedWaveNet.h"', 'namespace sc::dsp::models', '{']
    args = [v for v in sys.argv[1:] if v != '--merge' and not v.startswith('--rest=')]
    rest_of = {n for v in sys.argv[1:] if v.startswith('--rest=') for n in v[7:].split(',')}
    kept = []
    if '--merge' in sys.argv:            # (the models already there, each from 'inline const' to its closing '};')
        names = {v.split('=')[0] for v in args}
        old = open(os.path.join(o.PLUGIN, 'Source', 'dsp', 'LearnedModels.h')).read().splitlines()
        block = None
        for line in old:
            if line.startswith('inline const '):
                block = [line]; name = line.split()[3]
            elif block is not None: block.append(line)
            if block is not None and line.endswith('};'):
                if name not in names: kept += block
                block = None
    lines += kept
    for item in args:
        name, file = item.split('=')
        file, _, floor_db = file.partition(':')        # (name=file.pt:-60 trims the post filter's tail at -60 dB)
        d = torch.load(os.path.join(NN, file))
        s = d['state']
        if 'ch' in d:                    # a WaveNet
            C, L = d['ch'], d['layers']
            dil = d.get('dil') or [2 ** (i % 12) for i in range(L)]
            post = trimmed(s["post"], float(floor_db) if floor_db else -80.0)
            lines.append(f'inline const WaveNetWeights {name} {{ {C}, {{ {", ".join(map(str, dil))} }}, {arr(s["pre"])},')
            lines.append(f'    {arr(post)},')
            lines.append(f'    {arr(s["wn.inp.weight"])}, {arr(s["wn.inp.bias"])},')
            for key in ('conv', 'res', 'skip'):
                lines.append('    { ' + ', '.join(arr(s[f'wn.{key}.{i}.weight']) for i in range(L)) + ' },')
                lines.append('    { ' + ', '.join(arr(s[f'wn.{key}.{i}.bias']) for i in range(L)) + ' },')
            # (with --rest: what the network settles to on silence, taken off its output bias, so silence in is
            # silence out)
            rest = wavenet_rest(s, d) if name in rest_of else 0.0
            lines.append(f'    {arr(s["wn.out.weight"])}, {lit(float(s["wn.out.bias"][0]) - rest)}{flags(d, s)} }};')
            print(name, 'WaveNet', C, 'channels', L, 'layers, post taps', len(post), 'output at rest %.3g taken off' % rest if rest else '')
            continue
        H = d['hidden']
        if d.get('cell') == 'lstm':      # a stacked LSTM
            Lr = d.get('layers', 1)
            lines.append(f'inline const LSTMWeights {name} {{ {H}, {Lr}, {arr(s["pre"])},')
            lines.append(f'    {arr(s["post"])},')
            for key in ('weight_ih', 'weight_hh', 'bias_ih', 'bias_hh'):
                lines.append('    { ' + ', '.join(arr(s[f'gru.{key}_l{k}']) for k in range(Lr)) + ' },')
            skip = float(d.get('skip', 1.0))
            # what the network settles to on silence (its biases drive it with no input), taken off its output bias, so
            # silence in is silence out; computed as LearnedLSTM.h computes (float, FastMath.h's tanh): the rest state
            # is sensitive to the activations through the slow cells. That rest state is also where a reset starts it
            # (as a module of the reference switched on behaves like one that ran on silence: MEASUREMENTS.md 14)
            rest, h0, c0 = lstm_rest(s, H, Lr)
            lines.append(f'    {arr(s["out.weight"])}, {lit(float(s["out.bias"][0]) - rest)}, {lit(skip)},')
            lines.append('    { ' + ', '.join(arr(v) for v in h0) + ' }, { ' + ', '.join(arr(v) for v in c0) + ' } };')
            print(name, 'LSTM', Lr, 'x', H, 'skip', skip, 'output at rest %.3g taken off' % rest)
            continue
        lines.append(f'inline const LearnedWeights {name} {{ {H}, {arr(s["pre"])},')
        lines.append(f'    {arr(s["post"])},')
        lines.append(f'    {arr(s["gru.weight_ih_l0"])}, {arr(s["gru.weight_hh_l0"])}, {arr(s["gru.bias_ih_l0"])}, {arr(s["gru.bias_hh_l0"])},')
        lines.append(f'    {arr(s["out.weight"])}, {lit(float(s["out.bias"][0]))} }};')
        print(name, 'hidden', H, 'post taps', len(s['post']))
    lines.append('}')
    open(os.path.join(o.PLUGIN, 'Source', 'dsp', 'LearnedModels.h'), 'w').write('\n'.join(lines) + '\n')
